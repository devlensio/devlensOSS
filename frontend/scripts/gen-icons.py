#!/usr/bin/env python3
"""One-off codegen: emit components/icons.tsx from react-icons barrels.

We inline ONLY the icons the app actually uses, so the dev/prod bundle stops
pulling 7k+ icon components out of the react-icons barrels (md alone is 4.97 MB
of compiled output for 2 icons).

Run from frontend/:  python3 scripts/gen-icons.py
"""
import json
import re
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BARRELS = {
    "hi2": ROOT / "node_modules/react-icons/hi2/index.mjs",
    "io5": ROOT / "node_modules/react-icons/io5/index.mjs",
    "md": ROOT / "node_modules/react-icons/md/index.mjs",
    "gr": ROOT / "node_modules/react-icons/gr/index.mjs",
}

# icon set -> barrel file (index.mjs is the only entrypoint react-icons ships)
BARRELS = {
    "hi2": ROOT / "node_modules/react-icons/hi2/index.mjs",
    "io5": ROOT / "node_modules/react-icons/io5/index.mjs",
    "md": ROOT / "node_modules/react-icons/md/index.mjs",
    "gr": ROOT / "node_modules/react-icons/gr/index.mjs",
}

def build_index():
    """name -> react-icons node tree, across every barrel we care about."""
    index = {}
    for pkg, path in BARRELS.items():
        if not path.exists():
            sys.exit(f"missing barrel: {path}")
        src = path.read_text()
        for m in re.finditer(
            r"export function (\w+) \(props\) \{\s*return GenIcon\((\{.*?\})\)\(props\);\s*\};", src, re.S
        ):
            index[m.group(1)] = (pkg, json.loads(m.group(2)))
    return index


def scan_used(index):
    """Find which catalogued icons the app actually renders as JSX."""
    files = (
        list(ROOT.glob("app/**/*.tsx"))
        + list(ROOT.glob("components/**/*.tsx"))
        + list(ROOT.glob("lib/**/*.ts*"))
    )
    used = {}
    for f in files:
        if f.name == "icons.tsx":
            continue
        src = f.read_text()
        for name in re.findall(r"<([A-Z]\w+)", src):
            if name in index:
                pkg = index[name][0]
                used.setdefault(pkg, set()).add(name)
    return used


CSS_ATTR = {
    "fill-rule": "fillRule",
    "clip-rule": "clipRule",
    "stroke-width": "strokeWidth",
    "stroke-linecap": "strokeLinecap",
    "stroke-linejoin": "strokeLinejoin",
    "stroke-miterlimit": "strokeMiterlimit",
    "stroke-dasharray": "strokeDasharray",
    "stroke-dashoffset": "strokeDashoffset",
    "stop-color": "stopColor",
    "gradient-units": "gradientUnits",
    "clip-path": "clipPath",
    "fill-opacity": "fillOpacity",
    "stroke-opacity": "strokeOpacity",
    "text-anchor": "textAnchor",
    "font-size": "fontSize",
    "font-family": "fontFamily",
}


def camel(key):
    return CSS_ATTR.get(key, key)


def render_node(node, indent=6):
    """Render a react-icons node tree as JSX."""
    pad = " " * indent
    tag = node["tag"]
    attrs = {camel(k): v for k, v in (node.get("attr") or {}).items()}
    # `xmlns` is emitted implicitly by React for <svg>; harmless to keep others.
    attrs.pop("xmlns", None)
    children = node.get("child") or []

    def fmt(v):
        if isinstance(v, bool):
            return "{" + ("true" if v else "false") + "}"
        if isinstance(v, (int, float)):
            return "{" + repr(v) + "}"
        return '"' + str(v).replace('"', '\\"') + '"'

    attr_src = " ".join(f"{k}={fmt(v)}" for k, v in attrs.items())
    if not children:
        return f"{pad}<{tag}{' ' + attr_src if attr_src else ''} />"
    inner = "\n".join(render_node(c, indent + 2) for c in children)
    return f"{pad}<{tag}{' ' + attr_src if attr_src else ''}>\n{inner}\n{pad}</{tag}>"


HEADER = '''/* AUTO-GENERATED by scripts/gen-icons.py — do not edit by hand.
 *
 * Why this file exists
 * --------------------
 * `react-icons` only ships barrel entrypoints (`react-icons/md/index.mjs`), so a
 * single named import drags the ENTIRE icon set into the module graph. Opening
 * one graph page compiled and served ~7.8 MB of icon components for the ~14
 * icons it actually renders (md alone: 4,341 icons / 4.97 MB, io5: 1,332 /
 * 1.70 MB, hi2: 972 / 1.16 MB). That dominated Turbopack's compile time and
 * heap, which is what made `next dev` crawl and eventually die of OOM.
 *
 * These are the exact same SVG definitions react-icons ships, inlined per icon,
 * with the same `size` / `title` / pass-through prop semantics as their
 * IconBase. Adding an icon means adding it here (and to the generator's scan).
 */
import type { CSSProperties, ReactNode, SVGProps } from "react";

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children"> {
  /** Edge length. Numbers become px. Defaults to 1em like react-icons. */
  size?: number | string;
  /** Optional accessible label; without it the icon is aria-hidden. */
  title?: string;
}

function Icon({
  attr,
  children,
  size = "1em",
  title,
  style,
  ...rest
}: IconProps & {
  attr: Record<string, string | number>;
  children: ReactNode;
}) {
  const labelled = !!title;
  return (
    <svg
      {...attr}
      height={size}
      width={size}
      aria-hidden={labelled ? undefined : true}
      role={labelled ? "img" : undefined}
      style={{ flexShrink: 0, lineHeight: 1, ...(style as CSSProperties) }}
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}
'''


def main():
    index = build_index()
    wanted = scan_used(index)
    if not wanted:
        sys.exit("no react-icons usages found — nothing to generate")

    missing = []
    body = []
    count = 0
    for pkg in sorted(wanted):
        body.append(f"\n// ── {pkg} " + "─" * 60 + "\n")
        for name in sorted(wanted[pkg]):
            data = index[name][1]
            count += 1
            attr = {camel(k): v for k, v in (data.get("attr") or {}).items()}
            attr.pop("xmlns", None)
            # Icon() already sets aria-hidden / role based on `title`.
            attr.pop("aria-hidden", None)
            children = "\n".join(render_node(c) for c in data.get("child") or [])
            attr_src = ", ".join(
                (f'{k}: "{v}"' if k.isidentifier() else f'"{k}": "{v}"') for k, v in attr.items()
            )
            body.append(
                f"export function {name}(props: IconProps) {{\n"
                f"  return (\n"
                f"    <Icon attr={{{{ {attr_src} }}}} {{...props}}>\n"
                f"{children}\n"
                f"    </Icon>\n"
                f"  );\n"
                f"}}\n"
            )
    if missing:
        sys.exit("icons not found in react-icons barrels:\n  " + "\n  ".join(missing))

    out = ROOT / "components/icons.tsx"
    out.write_text(HEADER + "".join(body))
    print(f"wrote {out.relative_to(ROOT)} with {count} icons")


if __name__ == "__main__":
    main()